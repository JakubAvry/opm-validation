"""SHACL shapes from the catalogue: katalog/pravidla.yaml (field "shape") -> opmvalid/tvary.ttl, and the status of
every checked rule.

The catalogue is the single source: a shape is written in the record of its rule and the Turtle file
is generated. A rule checked by SHACL either has its own shape or names the shapes it shares in check.plan
("Shared shape of OPM-x-y"); its check.status is "implemented" exactly when all of them exist. A rule checked by
the grammar (and the checks of opmvalid/syntax.py) is "implemented" exactly when a test shows it: a valid sentence
of testy/vety_platne.txt names it, or a case of testy/vety_neplatne.txt expects its code or names it in covers=.

Usage (in the repository root):
  python katalog/tvary.py --check   generated text equals opmvalid/tvary.ttl, statuses agree (exit 0 / 1)
  python katalog/tvary.py --write   write opmvalid/tvary.ttl and set check.status in the catalogue
  python katalog/tvary.py --list    also list the grammar rules without a test
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "katalog" / "pravidla.yaml"
TARGET = ROOT / "opmvalid" / "tvary.ttl"
VALID = ROOT / "testy" / "vety_platne.txt"
INVALID = ROOT / "testy" / "vety_neplatne.txt"
ID = re.compile(r"OPM-[0-9A-Z]+-\d+|OPC-\d+")

HEADER = '''# GENERATED by katalog/tvary.py from katalog/pravidla.yaml (field "shape"); do not edit by hand.
# SHACL shapes for the catalogue rules. Each shape carries opm:rule (catalogue id) and opm:profile
# (iso / opcloud / both). Messages here are short; the report text comes from the catalogue.
# SHACL Core wherever it suffices; SHACL-SPARQL only where Core does not.

@prefix sh:   <http://www.w3.org/ns/shacl#> .
@prefix opm:  <https://example.org/opm#> .
@prefix opms: <https://example.org/opm/shapes#> .
@prefix rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .
@prefix owl:  <http://www.w3.org/2002/07/owl#> .

opms:prefixes a owl:Ontology ;
    sh:declare [ sh:prefix "opm" ; sh:namespace "https://example.org/opm#"^^xsd:anyURI ] ,
               [ sh:prefix "xsd" ; sh:namespace "http://www.w3.org/2001/XMLSchema#"^^xsd:anyURI ] ,
               [ sh:prefix "rdf" ; sh:namespace "http://www.w3.org/1999/02/22-rdf-syntax-ns#"^^xsd:anyURI ] .
'''
SECTIONS = [str(n) for n in range(6, 15)] + ["A", "B", "OPC"]


def order(rule_id: str) -> tuple:
    parts = rule_id.split("-")
    section = "OPC" if parts[0] == "OPC" else parts[1]
    return SECTIONS.index(section), int(parts[-1])


def title(section: str) -> str:
    return {"A": "Annex A", "B": "Annex B (W)", "OPC": "OPCloud profile"}.get(section, f"chapter {section}")


def generate(rules: list) -> str:
    out, last = [HEADER], None
    for r in sorted((r for r in rules if r.get("shape")), key=lambda r: order(r["id"])):
        section = SECTIONS[order(r["id"])[0]]
        if section != last:
            out.append(f"# {'-' * 94} {title(section)}\n")
            last = section
        out.append(r["shape"].rstrip("\n") + "\n")
    return "\n".join(out)


def implemented(rules: list) -> set:
    """Rules with their own shape, and rules whose shared shapes all exist."""
    done = {r["id"] for r in rules if r.get("shape")}
    changed = True
    while changed:                                    # shared shapes may point to rules that share shapes too
        changed = False
        for r in rules:
            check = r.get("check") or {}
            refs = re.findall(r"OPM-[0-9A-Z]+-\d+|OPC-\d+", str(check.get("plan", "")))
            if (r["id"] not in done and check.get("by") == "shacl" and "Shared shape" in str(check.get("plan"))
                    and refs and all(x in done for x in refs)):
                done.add(r["id"])
                changed = True
    return done


def evidence() -> dict:
    """Catalogue id -> the test lines that show it (valid sentences, invalid cases)."""
    ev = defaultdict(list)
    for n, line in enumerate(VALID.read_text(encoding="utf-8").splitlines(), 1):
        parts = line.split("\t")
        if line.strip() and not line.startswith("#") and len(parts) == 4:
            for rid in ID.findall(parts[2]):
                ev[rid].append(f"{VALID.name}:{n}")
    for n, line in enumerate(INVALID.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("== "):
            head = line[3:].split("|")
            named = ID.findall(head[0]) + [x for p in head[1:] if p.strip().startswith("covers=") for x in ID.findall(p)]
            for rid in named:
                ev[rid].append(f"{INVALID.name}:{n}")
    return ev


def wanted(rules: list) -> dict:
    """Rule id -> the status it should have (SHACL: shapes exist; grammar: a test shows it)."""
    done, ev = implemented(rules), evidence()
    out = {}
    for r in rules:
        by = (r.get("check") or {}).get("by")
        if by == "shacl":
            out[r["id"]] = "implemented" if r["id"] in done else "planned"
        elif by == "grammar":
            out[r["id"]] = "implemented" if ev.get(r["id"]) else "planned"
    return out


def set_statuses(text: str, rules: list) -> str:
    """check.status of every SHACL and grammar rule as wanted() says (edits the YAML text, keeps its layout)."""
    want_of = wanted(rules)
    for r in rules:
        check = r.get("check") or {}
        want = want_of.get(r["id"])
        if want is None or check.get("status") == want:
            continue
        i = text.index(f"  - id: {r['id']}\n")
        j = text.index(f"      status: {check.get('status')}\n", i)
        text = text[:j] + f"      status: {want}\n" + text[j + len(f"      status: {check.get('status')}\n"):]
    return text


def problems(rules: list) -> list:
    """Shapes and statuses that do not agree."""
    found = []
    by_id = {r["id"]: r for r in rules}
    for r in rules:
        check = r.get("check") or {}
        if r.get("shape"):
            if f'opm:rule "{r["id"]}"' not in r["shape"]:
                found.append(f'{r["id"]}: shape without opm:rule "{r["id"]}"')
            if check.get("by") != "shacl":
                found.append(f"{r['id']}: shape, but check.by is {check.get('by')}")
    for rid, want in wanted(rules).items():
        status = (by_id[rid].get("check") or {}).get("status")
        if status != want:
            found.append(f"{rid}: status {status}, should be {want}")
    unknown = {x for r in rules for x in re.findall(r"OPM-[0-9A-Z]+-\d+", str((r.get("check") or {}).get("plan", "")))
               if x not in by_id}
    found += [f"plan refers to an unknown rule {x}" for x in sorted(unknown)]
    found += [f"a test names an unknown rule {x}" for x in sorted(set(evidence()) - set(by_id))]
    return found


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    source = CATALOGUE.read_text(encoding="utf-8")
    rules = yaml.safe_load(source)["rules"]
    text = generate(rules)
    if "--write" in argv:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
        fixed = set_statuses(source, rules)
        if fixed != source:
            CATALOGUE.write_text(fixed, encoding="utf-8", newline="\n")
            rules = yaml.safe_load(fixed)["rules"]
    found = problems(rules)
    if TARGET.read_text(encoding="utf-8") != text:
        found.append(f"{TARGET.relative_to(ROOT)} differs from the catalogue (run --write)")
    shacl = [r for r in rules if (r.get("check") or {}).get("by") == "shacl"]
    print(f"rules checked by SHACL {len(shacl)}: own shape {sum(bool(r.get('shape')) for r in shacl)}, "
          f"implemented {sum(r['check'].get('status') == 'implemented' for r in shacl)}, "
          f"planned {sum(r['check'].get('status') == 'planned' for r in shacl)}")
    grammar = [r for r in rules if (r.get("check") or {}).get("by") == "grammar"]
    print(f"rules checked by the grammar {len(grammar)}: "
          f"implemented (shown by a test) {sum(r['check'].get('status') == 'implemented' for r in grammar)}, "
          f"planned {sum(r['check'].get('status') == 'planned' for r in grammar)}")
    if "--list" in argv:
        for r in rules:
            if (r.get("check") or {}).get("status") == "planned":
                print(f"  planned {r['id']} ({r['check']['by']}): {' '.join(r['rule'].split())[:110]}")
    for p in found:
        print("  problem:", p)
    print(f"problems {len(found)}")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
